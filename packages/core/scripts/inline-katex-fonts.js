/**
 * 构建脚本：将 KaTeX 字体内联到 CSS 中
 * 生成包含 base64 字体的 CSS 文件
 */
/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require("fs");
const path = require("path");

// 路径配置（pnpm 结构）
const katexDir = path.resolve(
  __dirname,
  "../../../node_modules/.pnpm/katex@0.16.27/node_modules/katex/dist",
);
const cssPath = path.join(katexDir, "katex.min.css");
const fontsDir = path.join(katexDir, "fonts");
const outputCssPath = path.resolve(__dirname, "../src/katex-inline.css");
const outputTsPath = path.resolve(__dirname, "../src/katex-inline-css.ts");

console.log("🚀 开始生成内联字体的 KaTeX CSS...");

// 读取 CSS 文件
let css = fs.readFileSync(cssPath, "utf-8");
console.log(`✅ 读取 CSS 文件: ${cssPath}`);

// 获取所有 woff2 字体文件
const woff2Files = fs
  .readdirSync(fontsDir)
  .filter((file) => file.endsWith(".woff2"));

console.log(`📦 找到 ${woff2Files.length} 个 woff2 字体文件`);

// 替换每个字体文件的 URL
let replacedCount = 0;
for (const filename of woff2Files) {
  const fontPath = path.join(fontsDir, filename);
  const fontBuffer = fs.readFileSync(fontPath);
  const base64 = fontBuffer.toString("base64");
  const dataUri = `data:font/woff2;base64,${base64}`;

  // 替换 CSS 中的 URL
  const pattern = new RegExp(`url\\(fonts/${filename}\\)`, "g");
  const matches = css.match(pattern);
  if (matches) {
    css = css.replace(pattern, `url(${dataUri})`);
    replacedCount++;
    console.log(`  ✓ ${filename} (${(fontBuffer.length / 1024).toFixed(1)}KB)`);
  }
}

// 移除其他格式的字体引用（woff 和 ttf）
css = css.replace(/,url\(fonts\/[^)]+\.woff\) format\("woff"\)/g, "");
css = css.replace(/,url\(fonts\/[^)]+\.ttf\) format\("truetype"\)/g, "");

// 添加文件头注释
const header = `/**
 * KaTeX CSS with Inlined Fonts (Base64)
 * 
 * This file is auto-generated by scripts/inline-katex-fonts.js
 * DO NOT EDIT MANUALLY!
 * 
 * To regenerate: npm run prepare
 * 
 * Original: katex@0.16.27
 * Generated: ${new Date().toISOString()}
 * Size: ~${(css.length / 1024).toFixed(1)}KB
 */

`;

// 写入 CSS 文件
fs.writeFileSync(outputCssPath, header + css, "utf-8");

// 写入 TypeScript 文件
const tsContent = `${header}
export const katexInlineCss = ${JSON.stringify(css)};
`;
fs.writeFileSync(outputTsPath, tsContent, "utf-8");

const cssSize = (fs.statSync(outputCssPath).size / 1024).toFixed(1);
const tsSize = (fs.statSync(outputTsPath).size / 1024).toFixed(1);
console.log(`\n✨ 成功生成内联文件:`);
console.log(`   CSS: ${outputCssPath} (${cssSize}KB)`);
console.log(`   TypeScript: ${outputTsPath} (${tsSize}KB)`);
console.log(`   替换字体: ${replacedCount}/${woff2Files.length}`);
